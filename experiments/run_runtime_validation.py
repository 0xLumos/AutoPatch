#!/usr/bin/env python3
"""
Runtime-validation experiment runner.

Produces the numbers the paper's runtime-validation table reports:
how many evaluated images passed build validation, runtime validation
(Tier 1 startup + Tier 2 introspection), and application-level
validation (Tier 3 probe).

Inputs
------
  --results     results.json from the main evaluation. Each entry must
                carry at least: image (or image_ref), strategy,
                build_success, acceptance. Patched-image references are
                read from `patched_image` / `patched_ref` when present.
  --manifest    dataset/smoke/manifest.yaml (per-image probe config).
  --strategy    which strategy's accepted images to validate
                (default AutoPatch).

Outputs
-------
  <out>/runtime_results.json   per-image tier outcomes (raw evidence)
  <out>/runtime_summary.json   aggregate counts used by the paper
  <out>/runtime_table.tex      LaTeX table ready to paste
  stdout                        human-readable summary

Every accepted image is started and probed; nothing is inferred or
extrapolated. Images whose patched reference is missing from the
results file are reported as `unavailable` rather than silently
dropped, so the denominator in the paper is always explicit.

Usage
-----
    python experiments/run_runtime_validation.py \
        --results research/results.json \
        --manifest dataset/smoke/manifest.yaml \
        --out research/runtime/
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path
from typing import Any, Dict, List, Optional

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))

from src.runtime_validator import (  # noqa: E402
    RuntimeValidationResult,
    Tier,
    TierOutcome,
    TierResult,
    summarize_results,
    validate_image,
)
from src.smoke_manifest import SmokeManifest, load_manifest  # noqa: E402


def _load_results(path: Path) -> List[Dict[str, Any]]:
    with open(path) as f:
        raw = json.load(f)
    if isinstance(raw, dict):
        return raw.get("results", [])
    return raw


def _image_ref(entry: Dict[str, Any]) -> Optional[str]:
    """The reference of the image to validate: the patched image when
    the entry describes an accepted transformation."""
    for key in ("patched_image", "patched_ref", "output_image",
                "result_image", "image_ref", "image"):
        v = entry.get(key)
        if isinstance(v, str) and v:
            return v
    return None


def _accepted_entries(
    entries: List[Dict[str, Any]], strategy: str
) -> List[Dict[str, Any]]:
    out = []
    for e in entries:
        if str(e.get("strategy", "")).lower() != strategy.lower():
            continue
        if not e.get("acceptance", e.get("accepted", False)):
            continue
        out.append(e)
    return out


def _unavailable_result(image: str, why: str) -> RuntimeValidationResult:
    r = RuntimeValidationResult(image_ref=image)
    r.tiers = [TierResult(tier=Tier.STARTUP,
                          outcome=TierOutcome.ERROR,
                          detail=why)]
    return r


def _latex_table(summary: Dict[str, Any], strategy: str,
                 n_accepted: int, n_built: int) -> str:
    tc = summary["tier_counts"]
    t1, t2, t3 = tc["startup"], tc["introspection"], tc["application"]
    rt_ok = summary["runtime_ok"]
    t3_app = summary["application_tier_applicable"]
    t3_rate = summary["application_tier_pass_rate"]
    t3_rate_s = f"{100.0 * t3_rate:.1f}\\%" if t3_rate is not None else "--"

    return f"""% Generated by experiments/run_runtime_validation.py
\\begin{{table}}[t]
\\centering
\\caption{{Runtime validation of accepted {strategy} transformations.
Tier~1 requires the container to remain running for the startup hold
window; Tier~2 invokes the entrypoint with a generic introspection
flag and treats a dynamic-loader or ABI error as a hard failure;
Tier~3 executes the operator-supplied application probe declared in
the published smoke manifest. Entrypoints that legitimately reject
introspection flags and images without a declared probe are recorded
as \\emph{{not applicable}} rather than as failures, so each tier's
pass rate has an explicit denominator.}}
\\label{{tab:runtime}}
\\begin{{tabular}}{{lrr}}
\\toprule
\\textbf{{Validation stage}} & \\textbf{{Passed}} & \\textbf{{Applicable}} \\\\
\\midrule
Build validation (rebuild succeeds) & {n_built} & {n_built} \\\\
Acceptance gate (Eq.~\\ref{{eq:accept}}) & {n_accepted} & {n_built} \\\\
Tier~1: startup & {t1['pass']} & {t1['pass'] + t1['fail']} \\\\
Tier~2: entrypoint introspection & {t2['pass']} & {t2['pass'] + t2['fail']} \\\\
Tier~3: application probe & {t3['pass']} & {t3_app} \\\\
\\midrule
\\textbf{{Runtime validated ($\\mathrm{{runtime\\_ok}}$)}} & \\textbf{{{rt_ok}}} & \\textbf{{{n_accepted}}} \\\\
\\bottomrule
\\end{{tabular}}\\\\[2pt]
\\footnotesize Tier~3 pass rate over applicable images: {t3_rate_s}.
\\end{{table}}
"""


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--results", required=True,
                    help="results.json from the main evaluation")
    ap.add_argument("--manifest", default="dataset/smoke/manifest.yaml")
    ap.add_argument("--strategy", default="AutoPatch")
    ap.add_argument("--out", default="research/runtime")
    ap.add_argument("--limit", type=int, default=None,
                    help="validate at most N images (smoke testing)")
    ap.add_argument("--advisory", action="store_true",
                    help="record failures without treating them as blocking")
    args = ap.parse_args()

    results_path = Path(args.results)
    if not results_path.is_file():
        print(f"results file not found: {results_path}", file=sys.stderr)
        return 1

    entries = _load_results(results_path)
    accepted = _accepted_entries(entries, args.strategy)
    built = [e for e in entries
             if str(e.get("strategy", "")).lower() == args.strategy.lower()
             and e.get("build_success", False)]

    if args.limit:
        accepted = accepted[: args.limit]

    manifest: Optional[SmokeManifest] = None
    mpath = Path(args.manifest)
    if mpath.is_file():
        manifest = load_manifest(str(mpath))
        print(f"Loaded manifest: {len(manifest)} images, "
              f"{manifest.application_probe_count} with application probes")
    else:
        print(f"No manifest at {mpath}; using defaults (Tier 1 + Tier 2 only)")

    print(f"\nValidating {len(accepted)} accepted {args.strategy} "
          f"transformations ({len(built)} built successfully)\n")

    results: List[RuntimeValidationResult] = []
    for i, entry in enumerate(accepted, 1):
        ref = _image_ref(entry)
        name = entry.get("image", ref or "?")
        if not ref:
            results.append(_unavailable_result(
                str(name), "no patched image reference in results file"))
            print(f"[{i}/{len(accepted)}] {name}: UNAVAILABLE (no ref)")
            continue

        spec = manifest.spec_for(ref) if manifest else None
        r = validate_image(ref, spec)
        results.append(r)

        tiers_s = " ".join(
            f"{t.tier.value[:5]}={t.outcome.value}" for t in r.tiers
        )
        verdict = "OK " if r.passed else "FAIL"
        print(f"[{i}/{len(accepted)}] {name}: {verdict}  {tiers_s} "
              f"({r.total_duration_s:.1f}s)")

    summary = summarize_results(results)
    summary["strategy"] = args.strategy
    summary["images_built"] = len(built)
    summary["images_accepted"] = len(accepted)
    summary["advisory_mode"] = bool(args.advisory)

    out_dir = Path(args.out)
    out_dir.mkdir(parents=True, exist_ok=True)

    raw_path = out_dir / "runtime_results.json"
    with open(raw_path, "w") as f:
        json.dump([r.to_dict() for r in results], f, indent=2, sort_keys=True)

    sum_path = out_dir / "runtime_summary.json"
    with open(sum_path, "w") as f:
        json.dump(summary, f, indent=2, sort_keys=True)

    tex_path = out_dir / "runtime_table.tex"
    tex_path.write_text(
        _latex_table(summary, args.strategy, len(accepted), len(built)),
        encoding="utf-8",
    )

    tc = summary["tier_counts"]
    print("\n" + "=" * 64)
    print(f"Build validation:        {len(built)} images rebuilt successfully")
    print(f"Acceptance gate:         {len(accepted)} accepted")
    print(f"Tier 1 startup:          {tc['startup']['pass']} pass, "
          f"{tc['startup']['fail']} fail, {tc['startup']['skip']} skip, "
          f"{tc['startup']['error']} error")
    print(f"Tier 2 introspection:    {tc['introspection']['pass']} pass, "
          f"{tc['introspection']['fail']} fail, "
          f"{tc['introspection']['skip']} n/a")
    print(f"Tier 3 application:      {tc['application']['pass']} pass, "
          f"{tc['application']['fail']} fail, "
          f"{tc['application']['skip']} n/a "
          f"(applicable: {summary['application_tier_applicable']})")
    print(f"runtime_ok overall:      {summary['runtime_ok']}/"
          f"{summary['images_evaluated']} "
          f"({100.0 * summary['runtime_ok_rate']:.1f}%)")
    print(f"Mean validation time:    {summary['mean_duration_s']:.1f}s per image")
    print("=" * 64)
    print(f"\nWrote {raw_path}")
    print(f"Wrote {sum_path}")
    print(f"Wrote {tex_path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
